from scipy.io import wavfile
from scipy.signal import get_window

def wav_to_dominant_freq_track(
    x: np.ndarray,
    frame_ms: float = 50.0,
    hop_ms: float = 10.0,
    fmin: float = 50.0,
    fmax: float = 5000.0,
    window: str = "hann",
):

    # mono + float32 in [-1, 1]
    if x.ndim > 1:
        x = x.mean(axis=1)
    if np.issubdtype(x.dtype, np.integer):
        x = x.astype(np.float32) / np.iinfo(x.dtype).max
    else:
        x = x.astype(np.float32)

    frame = max(8, int(round(frame_ms * fs / 1000.0)))
    hop   = max(1, int(round(hop_ms   * fs / 1000.0)))

    win = get_window(window, frame, fftbins=True).astype(np.float32)

    nfft = 1 << int(np.ceil(np.log2(frame)))  # next pow2
    freqs = np.fft.rfftfreq(nfft, d=1/fs)

    band = (freqs >= fmin) & (freqs <= fmax)
    band_idx = np.where(band)[0]
    if band_idx.size == 0:
        raise ValueError("No FFT bins in [fmin, fmax]. Increase fmax or reduce nfft/frame.")

    # number of complete frames
    n_frames = 1 + (len(x) - frame) // hop if len(x) >= frame else 0
    if n_frames == 0:
        return np.array([], dtype=float), np.array([], dtype=float)

    times = (np.arange(n_frames) * hop + frame/2) / fs
    ftrack = np.empty(n_frames, dtype=np.float32)

    for i in range(n_frames):
        start = i * hop
        seg = x[start:start+frame]
        seg = (seg - seg.mean()) * win

        spec = np.fft.rfft(seg, n=nfft)
        mag = np.abs(spec)

        k = band_idx[np.argmax(mag[band_idx])]

        # parabolic interpolation for sub-bin accuracy (optional but nice)
        if 1 <= k < len(mag) - 1:
            a, b, c = mag[k-1], mag[k], mag[k+1]
            denom = (a - 2*b + c)
            p = 0.0 if denom == 0 else 0.5 * (a - c) / denom
            k = k + p

        ftrack[i] = (k * fs) / nfft

    return times, ftrack






